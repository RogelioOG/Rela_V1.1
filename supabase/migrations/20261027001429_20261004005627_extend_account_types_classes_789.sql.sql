/*
# Extend account types to include Colombian PUC classes 7, 8, 9

## Changes
1. Drops the old CHECK constraint on accounts.type that only allowed 5 types.
2. Adds a new CHECK constraint that includes:
   - activo, pasivo, patrimonio, ingreso, gasto (existing)
   - costo (Clase 7 — Costos de Producción)
   - orden_deudora (Clase 8 — Cuentas de Orden Deudoras)
   - orden_acreedora (Clase 9 — Cuentas de Orden Acreedoras)
3. These new types are NOT auto-generated by ensure_default_accounts() — they
   are only available for manual account creation and mapping.
*/

ALTER TABLE public.accounts DROP CONSTRAINT IF EXISTS accounts_type_check;

ALTER TABLE public.accounts ADD CONSTRAINT accounts_type_check
  CHECK (type IN ('activo', 'pasivo', 'patrimonio', 'ingreso', 'gasto', 'costo', 'orden_deudora', 'orden_acreedora'));